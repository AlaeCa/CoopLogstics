
-- CoopLogistics - Initial schema
-- PostgreSQL 16 / Flyway V1

CREATE TABLE cooperative (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             nom VARCHAR(150) NOT NULL,
                             ice VARCHAR(30) NOT NULL UNIQUE,
                             adresse_siege TEXT,
                             ville VARCHAR(100),
                             telephone VARCHAR(30),
                             statut VARCHAR(30) NOT NULL
);

CREATE TABLE utilisateur (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             keycloak_id VARCHAR(100) NOT NULL UNIQUE,
                             cooperative_id BIGINT,
                             nom VARCHAR(100) NOT NULL,
                             prenom VARCHAR(100),
                             email VARCHAR(255) NOT NULL,
                             role VARCHAR(40) NOT NULL,
                             actif BOOLEAN NOT NULL DEFAULT TRUE,
                             date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_utilisateur_cooperative FOREIGN KEY (cooperative_id)
                                 REFERENCES cooperative(id)
);

CREATE TABLE adresse (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         libelle VARCHAR(255) NOT NULL,
                         ville VARCHAR(100) NOT NULL,
                         latitude NUMERIC(10,7),
                         longitude NUMERIC(10,7),
                         contact VARCHAR(150),
                         CONSTRAINT ck_adresse_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
                         CONSTRAINT ck_adresse_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE commande (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          cooperative_id BIGINT NOT NULL,
                          adresse_origine_id BIGINT NOT NULL,
                          adresse_destination_id BIGINT NOT NULL,
                          reference VARCHAR(80) NOT NULL UNIQUE,
                          date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          statut VARCHAR(30) NOT NULL,
                          poids_total NUMERIC(12,3) NOT NULL DEFAULT 0,
                          volume_total NUMERIC(12,3) NOT NULL DEFAULT 0,
                          livraison_souhaitee TIMESTAMP,
                          CONSTRAINT fk_commande_cooperative FOREIGN KEY (cooperative_id)
                              REFERENCES cooperative(id),
                          CONSTRAINT fk_commande_origine FOREIGN KEY (adresse_origine_id)
                              REFERENCES adresse(id),
                          CONSTRAINT fk_commande_destination FOREIGN KEY (adresse_destination_id)
                              REFERENCES adresse(id),
                          CONSTRAINT ck_commande_poids CHECK (poids_total >= 0),
                          CONSTRAINT ck_commande_volume CHECK (volume_total >= 0)
);

CREATE TABLE colis (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       commande_id BIGINT NOT NULL,
                       code_suivi VARCHAR(80) NOT NULL UNIQUE,
                       designation VARCHAR(255) NOT NULL,
                       poids NUMERIC(12,3) NOT NULL,
                       volume NUMERIC(12,3) NOT NULL,
                       fragile BOOLEAN NOT NULL DEFAULT FALSE,
                       perissable BOOLEAN NOT NULL DEFAULT FALSE,
                       type_produit VARCHAR(100),
                       CONSTRAINT fk_colis_commande FOREIGN KEY (commande_id)
                           REFERENCES commande(id),
                       CONSTRAINT ck_colis_poids CHECK (poids > 0),
                       CONSTRAINT ck_colis_volume CHECK (volume >= 0)
);

CREATE TABLE facture (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         cooperative_id BIGINT NOT NULL,
                         commande_id BIGINT NOT NULL UNIQUE,
                         numero VARCHAR(80) NOT NULL UNIQUE,
                         date_emission DATE NOT NULL,
                         montant_total NUMERIC(12,2) NOT NULL,
                         statut_paiement VARCHAR(30) NOT NULL,
                         CONSTRAINT fk_facture_cooperative FOREIGN KEY (cooperative_id)
                             REFERENCES cooperative(id),
                         CONSTRAINT fk_facture_commande FOREIGN KEY (commande_id)
                             REFERENCES commande(id),
                         CONSTRAINT ck_facture_montant CHECK (montant_total >= 0)
);

CREATE TABLE reclamation (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             commande_id BIGINT NOT NULL,
                             type VARCHAR(50) NOT NULL,
                             description TEXT NOT NULL,
                             statut VARCHAR(30) NOT NULL,
                             date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_reclamation_commande FOREIGN KEY (commande_id)
                                 REFERENCES commande(id)
);

CREATE INDEX idx_utilisateur_cooperative ON utilisateur(cooperative_id);
CREATE INDEX idx_commande_cooperative ON commande(cooperative_id);
CREATE INDEX idx_commande_origine ON commande(adresse_origine_id);
CREATE INDEX idx_commande_destination ON commande(adresse_destination_id);
CREATE INDEX idx_colis_commande ON colis(commande_id);
CREATE INDEX idx_facture_cooperative ON facture(cooperative_id);
CREATE INDEX idx_reclamation_commande ON reclamation(commande_id);
